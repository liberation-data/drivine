/**
 * Writes src/backend/postgres/PostgresStoreText.ts from drivine4j's store: the block that makes a Postgres graph, its
 * tables, functions and version, so that Drivine makes the store drivine4j makes, byte for byte, and a graph written
 * from the JVM and from Node is one.
 *
 * Give it the text of drivine4j's `PostgresGraph("zzgraphzz").ensuring` and `PostgresGraph.VERSION`, each in a file:
 *
 *     node scripts/postgres-store.js ensuring.sql version.txt
 *
 * Run it again whenever drivine4j's store changes: its version says when it has.
 */
const fs = require('fs');
const path = require('path');

const [ensuringFile, versionFile] = process.argv.slice(2);
if (!ensuringFile || !versionFile) {
    console.error('usage: node scripts/postgres-store.js <ensuring.sql> <version.txt>');
    process.exit(1);
}
const ensuring = fs.readFileSync(ensuringFile, 'utf8');
const version = fs.readFileSync(versionFile, 'utf8').trim();
const lines = ensuring.split('\n').map((it) => `    ${JSON.stringify(it)}`);
const text = `// Generated by scripts/postgres-store.js from drivine4j's PostgresGraph: do not edit.

/** The version of drivine4j's store this block makes: the node table's comment says which made a store. */
export const POSTGRES_STORE_VERSION = ${JSON.stringify(version)};

/** What stands for the graph's name in the block. */
export const GRAPH_PLACEHOLDER = 'zzgraphzz';

/** drivine4j's block that makes a graph's store, its name written as GRAPH_PLACEHOLDER. */
export const POSTGRES_STORE_ENSURING = [
${lines.join(',\n')}
].join('\\n');
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'backend', 'postgres', 'PostgresStoreText.ts'), text);
